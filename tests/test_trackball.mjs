import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../tools/ply_viewer/trackball.js',import.meta.url),'utf8');
const {rotate,sphere,trackball,dot}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const rect={left:0,top:0,width:400,height:400},identity=[0,0,0,1];
const near=(a,b)=>a.forEach((v,i)=>assert.ok(Math.abs(v-b[i])<1e-9,`${a} != ${b}`));
near(sphere(200,200,rect),[0,0,1]);
near(trackball(identity,[0,0,1],[0,0,1]),identity);
const from=sphere(200,200,rect),to=sphere(300,200,rect);
const q=trackball(identity,from,to);
near(rotate(q,to),from);
const antipodal=trackball(identity,[1,0,0],[-1,0,0]);
near(rotate(antipodal,[-1,0,0]),[1,0,0]);
const roll=trackball(identity,sphere(350,200,rect),sphere(200,50,rect));
assert.ok(Math.abs(roll[2])>.1,'edge drag should allow roll');
let cumulative=identity;
for(let i=0;i<1000;i++)cumulative=trackball(cumulative,sphere(i%400,40,rect),sphere((i+10)%400,70,rect));
assert.ok(Math.abs(Math.hypot(...cumulative)-1)<1e-10);
const basis=[[1,0,0],[0,1,0],[0,0,1]].map(v=>rotate(cumulative,v));
assert.ok(Math.abs(dot(basis[0],basis[1]))<1e-10);
near(trackball(q,to,from),identity);
console.log('Trackball passed: identity, direction, antipodal rotation, roll, inverse, and stable orthonormal basis.');
