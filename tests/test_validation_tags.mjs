import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../tools/ply_viewer/tags.js',import.meta.url),'utf8');
const {location,matches,tagsFor,validateRules}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const sample={dataset:'val',filename:'Town05_run/scenes/scene1/samples/000033/front',town:'Town05',camera:'front'};
const scene='Town05_run/scenes/scene1';
const rule={id:'one',type:'rule',name:'intersection',dataset:'val',map:'Town05',scene,prefix:'',camera:'',start:30,end:33};
assert.deepEqual(location(sample),{map:'Town05',scene,frame:33});
assert.equal(matches(sample,rule),true);
assert.equal(matches(sample,{...rule,end:32}),false);
assert.equal(matches({...sample,filename:sample.filename.replace('scene1','scene2')},rule),false);
assert.equal(matches({...sample,dataset:'train'},rule),false);
assert.equal(matches(sample,{...rule,camera:'right'}),false);
assert.equal(matches(sample,{...rule,prefix:'Town01'}),false);
assert.equal(location({...sample,map_file:'/maps/custom.xodr'}).map,'/maps/custom.xodr');
assert.deepEqual(tagsFor(sample,[rule,{...rule,id:'two'}]),['intersection']);
assert.equal(matches(sample,{type:'samples',keys:[JSON.stringify([sample.dataset,sample.filename])]}),true);
assert.throws(()=>validateRules({version:1,rules:[{...rule,start:34}]}));
assert.throws(()=>validateRules({version:1,rules:[{...rule,scene:''}]}));
assert.throws(()=>validateRules({version:1,rules:[rule,rule]}));
assert.throws(()=>validateRules({version:1,rules:[{...rule,start:1.5}]}));
assert.equal(validateRules({version:1,rules:[rule]}).length,1);
console.log('Tag matching, inclusive ranges, scene isolation, deduplication and import validation passed');
